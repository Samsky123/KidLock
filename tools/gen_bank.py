# ---------------------------------------------------------------- 基础工具

def q(title, correct, others, diff=1):
    """构造一道题：把正确答案混进选项里，并算出下标。"""
    correct = str(correct)
    options = [correct] + [str(o) for o in others]
    seen, uniq = set(), []
    for o in options:
        if o not in seen:
            seen.add(o)
            uniq.append(o)
    RNG.shuffle(uniq)
    return {
        "title": title,
        "options": uniq,
        "answer": uniq.index(correct),
        "difficulty": diff,
    }


def A(title, correct, *others, diff=1):
    """简写：A(题干, 正确答案, 错误选项1, 错误选项2, 错误选项3)。"""
    return q(title, correct, others, diff)


def wrong_nums(ans, n=3, low=0):
    """围绕正确答案生成 n 个互不相同的干扰项（整数）。"""
    picked, guard = set(), 0
    while len(picked) < n and guard < 300:
        delta = RNG.choice([-20, -10, -5, -3, -2, -1, 1, 2, 3, 5, 10, 20])
        v = ans + delta
        if v != ans and v >= low:
            picked.add(v)
        guard += 1
    k = 1
    while len(picked) < n:
        picked.add(ans + k)
        k += 1
    return sorted(picked)


def num_q(title, ans, diff=1, low=0):
    return q(title, ans, wrong_nums(ans, low=low), diff)


def group(grade, subject, unit, questions, edition="通用"):
    return {
        "grade": grade,
        "subject": subject,
        "edition": edition,
        "unit": unit,
        "questions": questions,
    }



# ---------------------------------------------------------------- 汇总与校验

def build():
    groups = []
    groups += math_g1() + math_g2() + math_g3() + math_g4() + math_g5() + math_g6()
    groups += chinese()
    groups += english()

    # 校验：每题必须有 4 个不重复选项、answer 下标合法
    errors = []
    total = 0
    for g in groups:
        for item in g["questions"]:
            total += 1
            opts = item["options"]
            if len(opts) != 4:
                errors.append(f"选项数不是 4：{g['grade']} {g['subject']} {item['title']} -> {opts}")
            if len(set(opts)) != len(opts):
                errors.append(f"选项重复：{g['grade']} {g['subject']} {item['title']} -> {opts}")
            if not (0 <= item["answer"] < len(opts)):
                errors.append(f"答案下标越界：{item['title']}")

    if errors:
        print("题库校验发现问题：")
        for e in errors:
            print("  -", e)
        raise SystemExit(1)

    data = {
        "version": 2,
        "editions": EDITIONS,
        "grades": GRADES,
        "groups": groups,
    }
    with open(OUT, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=1)

    # 统计
    stat = {}
    for g in groups:
        key = (g["grade"], g["subject"])
        stat[key] = stat.get(key, 0) + len(g["questions"])

    print(f"已写入 {OUT}")
    print(f"分组 {len(groups)} 个，题目 {total} 道")
    print("按年级 / 学科：")
    for grade in GRADES:
        row = [f"{s} {stat.get((grade, s), 0):>3}" for s in ("语文", "数学", "英语")]
        print(f"  {grade}  " + "  ".join(row))


if __name__ == "__main__":
    build()
